export function getDeck(id) {
    return DECKS.find(item => item.id === id) ?? null;
}

// デッキのカードIDの配列（{ id: 枚数 } を展開したもの）
export function expandDeck(item) {
    return Object.entries(item.cards).flatMap(([id, count]) => Array(count).fill(id));
}
